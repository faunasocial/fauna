"""Generate per-platform element-id constants from tests/e2e-unified/ui.yaml.

Targets:
  - Rust:   libs/fauna-ui-ids/src/lib.rs          (shared crate — tui + linux)
  - TS:     apps/fauna-web/src/lib/generated/uiIds.ts
  - Swift:  apps/fauna-apple/FaunaKit/Sources/FaunaKit/Generated/UiIds.swift
  - Kotlin: apps/fauna-android/app/src/main/kotlin/social/fauna/generated/UiIds.kt
  - C#:     apps/fauna-windows/FaunaApp/FaunaApp/Generated/UiIds.cs
  - Python: tests/e2e-unified/generated/ui_ids.py

Owner doc: docs/goal/architecture/build-system.md § Generated element-id constants.

Three decisions a later session would otherwise re-derive:

0. **Nothing here is spelled twice.** "What ui.yaml declares" is imported from
   `scripts/lint-ui-registry.py`; how an id becomes a member name is imported from
   `scripts/ui_id_names.py`, which the two ui lints import as well so they can
   recognise a *constant reference* as an implementation once an app adopts.

1. **"What ui.yaml declares" is imported from `scripts/lint-ui-registry.py`, never
   reimplemented.** That script is the gate which decides whether an id an app renders
   is declared; a generator with its own second answer could emit a constant the gate
   rejects, or omit one it demands. One definition, so they cannot drift. The lint's
   own history is the argument: three separate id-list keys (`components:`,
   `navigation.tabs`, `children:`) were each found unwalked *after* it shipped, and a
   private copy here would have inherited exactly those blind spots and then diverged
   as they were fixed.

2. **The declared set is filtered to the element-id shape** (`KEBAB` below, the same
   class the lint uses to recognise a rendered id). `collect_declared` deliberately
   also returns top-level `pages:`/`onboarding:` block *names* — 43 of them, snake_case
   things like `feed`, `devices`, `dns_config` — because an app may render a block's
   own key as an id. Those are page names, not elements, and emitting them would both
   produce junk constants and create a real collision: the onboarding page
   `launch_instance_chooser` and the registry element `launch-instance-chooser` derive
   the same `LAUNCH_INSTANCE_CHOOSER`. The shape filter drops the page names and the
   collision together, on a rule rather than an exception list.

3. **No per-constant doc comments** (the registry rows carry `type` + `description`).
   The id name is the documentation, and 1567 free-text descriptions round-tripped
   through six languages' string-literal rules is escaping risk bought for very little.
   ui.yaml stays the place to read what an id means.

Derived member names are checked for collisions in every language *before* anything is
written: two ids that differ only where a separator was (`a-b_c` vs `a-b-c`) would
silently collapse into one constant, so a collision is a hard error naming both ids.
Reserved words are escaped rather than assumed absent — none collide today across 1604
ids, and a future id must not be the thing that discovers that.

Per-file byte comparison before writing is load-bearing, not boilerplate: the Rust
target lands inside `libs/`, which every `wasm-<name>` build gate keys on by mtime, so
rewriting an unchanged file would silently mark all of them stale
(build-system.md § How the gate works).

Gated features (2026-08-17)
---------------------------

ui.yaml's `gated_features:` block says which ids belong to a controversial-class feature
(`docs/goal/architecture/dynamic-features.md` § The gated-feature registry). A store-safe
artifact must not carry those ids **structurally** — criterion 1 of § What "completely
compiled away" means — and an unqualified table of every id is exactly the structural
carry that criterion forbids. So each target emits its gated families behind that
family's own compile condition, which differs per platform family and, for two targets,
does not exist at all. `GATED_EMISSION` below is that per-target answer, with the reason
recorded on every entry — including the two that deliberately emit nothing special,
because "this target needs no gate" is a claim about the language and it must be
readable, not inferred from an absence.
"""
