  // Shapes mirror the shared `MailSettingsSnapshot` serde JSON (snake_case across
  // the serde_wasm_bindgen boundary). Typed locally over the `any` snapshot.
  interface CredentialRow {
    credential_id: string;
    display_name: string;
    kind: string; // "OAuthBearer" | "Plain"
    created_at: number;
    // The concrete MUA username with the `+<credential_id>` suffix, `default`→bare
    // rule, and domain already resolved in shared Rust — only `{handle}` remains
    // (mail-settings.md § State). Rendered via the shared `resolveMuaUsername`.
    mua_username: string;
    // Succession's *Compromised — access revoked* state (`mail-credentials.md`
    // § Rotation and recovery → Succession) — the row survives so the user
    // knows what to set up again, but must never read as usable.
    revoked: boolean;
  }
  interface MuaInstructions {
    imap_host: string;
    imap_port: number;
    smtp_host: string;
    smtp_port: number;
    // CalDAV server URL host + port (= `mail.<domain>` / 443). The one shared
    // credential AUTHs CalDAV too, so a CalDAV-only actor needs these connection
    // details (mail-settings.md § CalDAV-only mailbox; caldav-server.md § Network
    // exposure). Additive over wasm — the snapshot JSON already carries them.
    caldav_host: string;
    caldav_port: number;
    // The full WebDAV collection-root URL to mount (`https://mail.<domain>/webdav/`,
    // or the bare locator + DAV port on a local-target box). A full URL, not a
    // host+port pair: no SRV autodiscovery exists for WebDAV, so this line is the
    // primary setup surface (mail-settings.md § WebDAV files). Built in shared Rust.
    webdav_url: string;
    username_format: string;
    auth_mechanism: string;
  }
  interface MailSnapshot {
    // True iff **email** (SMTP + IMAP) is on for this actor (keys on the
    // `mail_enabled` flag, NOT merely on having an MSEK). A CalDAV-only actor
    // reads `enabled: false` with `caldav_enabled: true`.
    enabled: boolean;
    // True iff **CalDAV** (calendar) is on, independent of email. Both ride the
    // one shared MSEK + `default` credential (caldav-server.md § Authentication —
    // "no separate CalDAV credential"), so the credential-management section +
    // serve-here toggle render whenever the mailbox is provisioned
    // (`enabled || caldav_enabled`), not only when email is on
    // (mail-settings.md § CalDAV-only mailbox).
    caldav_enabled: boolean;
    // True iff **CardDAV** (contacts / address book) is on — the contacts
    // sibling of `caldav_enabled`, same shared MSEK + credential, so it joins
    // the credential-section render predicate
    // (`enabled || caldav_enabled || carddav_enabled`;
    // carddav-server.md § Independent enablement).
    carddav_enabled: boolean;
    // True iff this actor serves >=1 folder over WebDAV (the per-actor serve
    // state, folded from `fauna.folders.list` — NOT the deployment-wide
    // `webdav_enabled` toggle, which defaults on). Joins the reachability
    // predicate and gates the MUA WebDAV URL row (webdav-server.md
    // § Independent enablement pt 1).
    serves_webdav_set: boolean;
    // The credential-management reachability predicate, computed once in shared
    // Rust: `enabled || caldav_enabled || carddav_enabled || serves_webdav_set`.
    // Read it — never re-derive it here (priority #2/#4).
    credential_management_reachable: boolean;
    // Per-actor "serve my mailbox over IMAP/CalDAV on this nest" flag (default
    // on). A nest-side flag, not synced — set via SetServingEnabled, read on
    // hydrate (mail-settings.md § Local IMAP/CalDAV-serving toggle).
    serving_enabled: boolean;
    credentials: CredentialRow[];
    pending_rotation: { credentials_remaining: string[] } | null;
    mua: MuaInstructions;
    // SettingsStatus is "Idle" / "Syncing" / { RotationInProgress: { credentials_remaining } }.
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    status: any;
    error: string | null;
  }

  let machine: WasmMailSettingsMachine | null = null;
  let snap = $state<MailSnapshot | null>(null);

  // The credential-management reachability predicate — email OR CalDAV OR CardDAV
  // on, OR >=1 folder served over WebDAV. All ride the one shared MSEK +
  // `default` credential, so the credential-management section (keys explainer,
  // credentials list, add/rotate) and the serve-here toggle render whenever a
  // mailbox exists or is needed, NOT only when email is on (mail-settings.md
  // § CalDAV-only mailbox). The email IMAP/SMTP connection block stays gated on
  // `enabled`. Computed once in shared Rust (`MailSettingsSnapshot::
  // credential_management_reachable`) — every app reads the field rather than
  // re-deriving the disjunction, so a future DAV sibling widens it in one place
  // (priority #2/#4).
  const mailbox = $derived(Boolean(snap?.credential_management_reachable));

  // Inline add-credential form (reveal, not modal — matches linux). The form is
  // opened from two entry points with different intent: the enabled-toggle
  // ('enable' → first-credential EnableMail) and the add-credential button
  // ('add' → AddCredential onto the existing mailbox). The intent is captured at
  // open time, mirroring the linux lead's `FormMode::Enable`/`FormMode::Add` — a
  // live-`snap.enabled` inference can't distinguish a CalDAV-only mailbox
  // (enabled=false but a mailbox/MSEK already exists, so add-credential must
  // dispatch AddCredential, never EnableMail which would turn email on).
  let formOpen = $state(false);
  let formIntent = $state<'enable' | 'add'>('enable');
  let nameInput = $state('Default');
  let isPlain = $state(false); // type-selector: false = OAUTHBEARER (default), true = PLAIN
  // PLAIN auto-generate (mail-add-credential-autogenerate-toggle): ON by default
  // (mail-credentials.md § Auto-generated bridge password). When on, the password
  // input holds a shared-Rust-generated a-zA-Z0-9 secret and is read-only; turning
  // it off enables manual entry (and, on an encrypted nest, the weak-password
  // warning). All decision logic is shared Rust (priority #2) — see applyAutogen.
  let autoGenerate = $state(true);
  let showWeakWarning = $state(false);
  let passwordInput = $state('');
  let showPassword = $state(false);
  let tokenShown = $state(''); // OAUTHBEARER one-time token reveal (after submit)
  // Every nest stores at rest encrypted (no-modes, ratified 2026-07-12 —
  // docs/goal/architecture/nest/storage-modes.md), so the manual-password
  // warning's `nest_encrypted` input is unconditionally true — the same
  // constant tui and apple pass (`warn_manual_password(auto, true)`).
  const nestEncrypted = true;

  // Rotate-keys confirm (inline reveal).
  let rotateOpen = $state(false);

  // Disable-mail confirm (destructive overlay — mail-settings.md § Disable mail).
  // Flipping the enabled-toggle off opens this; confirming dispatches DisableMail
  // (bulk-revoke every credential + clear the MSEK). The toggle keeps rendering
  // "Mail enabled" until the confirmed DisableMail re-render flips snap.enabled —
  // no lying off-state, mirroring the linux lead's snap-back-on behavior.
  let disableConfirmOpen = $state(false);

  // Per-credential secret reveal (mail-settings.md § Credentials list). The secret
  // is NOT in the passive snapshot — clicking reveal fetches it on demand from the
  // client's own `fauna.state.mail` entries via the shared `MailSettingsMachine::reveal_credential_secret`
  // (wasm `revealCredentialSecret`), mirroring the shown-once reveal at credential-add
  // time. Held hidden by default and never logged or persisted; a second click hides it.
  let revealedSecrets = $state<Record<string, string>>({});

  async function toggleSecret(credentialId: string): Promise<void> {
    if (credentialId in revealedSecrets) {
      const next = { ...revealedSecrets };
      delete next[credentialId];
      revealedSecrets = next;
      return;
    }
    if (!machine) return;
    try {
      const secret = (await machine.revealCredentialSecret(credentialId)) as string;
      revealedSecrets = { ...revealedSecrets, [credentialId]: secret };
    } catch (e) {
      error = String(e);
    }
  }

  // The `mail-settings-status-indicator` decision (Syncing / RotationInProgress /
  // Idle-gated-on-enabled → which `settings.mail.status_*` key) lives in shared
  // Rust `fauna_client_mail_settings::settings_status_label` (over wasm) — the
  // same source of truth the native apps consume via UniFFI, so web no longer
  // hand-rolls the ternary. `Idle` reads `status_enabled` ONLY when mail is on
  // (a disabled or pre-hydrate mailbox reads `status_disabled` — the cross-app
  // "mail enabled" signal the e2e `wait_for_enabled_status` probe reads).
  // mail-settings.md § the status indicator.
  function statusLabel(status: unknown, enabled: boolean): string {
    return resolveLocalized(settingsStatusLabel(status, enabled));
  }

  // The exact MUA username for a credential. The shared snapshot already resolved
  // the `+<credential_id>` suffix, the `default`→bare rule, and the domain into
  // `MailCredentialSummary.mua_username` (mail-settings.md § State) — only
  // `{handle}` is left, which we substitute via the shared `resolveMuaUsername`
  // (priority #2: web no longer re-derives the bug-prone suffix, the gap that let
  // a user pick the wrong bare form for a `+suffix` credential). Callers run after
  // `ensureWasm()` — credential rows render only once the hydrated snapshot exists.
  function muaUsername(template: string): string {
    return resolveMuaUsername(template, $identity?.handle ?? '');
  }

  function applySnapshot(): void {
    if (!machine) return;
    snap = machine.snapshot() as unknown as MailSnapshot;
    if (snap?.error) error = snap.error;
  }

  onMount(async () => {
    const id = $identity;
    if (!id?.secretHex) return;
    try {
      await ensureWasm();
      machine = await mailSettingsMachine(id.secretHex);
      await machine.hydrate();
      applySnapshot();
    } catch (e) {
      error = e instanceof Error ? e.message : String(e);
    }
    // Read the nest's storage mode once — only an ENCRYPTED nest surfaces the
  });

  // The post-store-ready aftermath pass settled — its last leg, the mail burn,
  // marks rows on the account's mail custody that this page's machine hydrated
  // before (succession-aftermath.md § Re-key scope → *Where the plane raises
  // run*). Re-read so a burn landing while the page is open shows its rows as
  // revoked, as the review surfaces re-read on the same hook.
  $effect(() => {
    if ($configStageSettled > 0 && machine) {
      void machine.hydrate().then(applySnapshot, () => {});
    }
  });

  // Click the enable toggle (mail-settings.md § Disable mail). Off → on: reveal the
  // first-credential form (EnableMail). On → off: open the destructive disable-confirm
  // overlay — the dialog is the real decision point, so the toggle keeps rendering
  // "Mail enabled" until a confirmed DisableMail flips snap.enabled (no lying off-state;
  // mirrors the linux lead's snap-back-on). Branch on the live snapshot, not a mode flag,
  // so a slow hydrate can't strand the wrong path.
  function onToggle(): void {
    if (snap?.enabled) {
      disableConfirmOpen = true;
      error = '';
    } else {
      // Enabling email from the toggle (works on a never-enabled OR a CalDAV-only
      // actor — EnableMail reuses the shared MSEK when one already exists).
      openForm('enable');
    }
  }

  function openAddCredential(): void {
    // Add a credential onto the existing mailbox (the button only renders when a
    // mailbox is provisioned, so the MSEK is always present → AddCredential).
    openForm('add');
  }

  function openForm(intent: 'enable' | 'add'): void {
    formIntent = intent;
    formOpen = true;
    nameInput = 'Default';
    isPlain = false;
    autoGenerate = true;
    showWeakWarning = false;
    passwordInput = '';
    showPassword = false;
    tokenShown = '';
    error = '';
  }

  // Select the PLAIN credential kind: reveal the password box and, since
  // auto-generate defaults ON, mint the first generated password into it.
  function selectPlain(): void {
    isPlain = !isPlain;
    if (isPlain) applyAutogen();
  }

  // Flip the auto-generate toggle and re-apply its effect on the password input.
  function onAutogenToggle(): void {
    autoGenerate = !autoGenerate;
    applyAutogen();
  }

  // Auto-generate ON (default): shared Rust mints a strong a-zA-Z0-9 password into
  // the read-only, revealed input, shown-once for the user to copy. OFF: clear it
  // for masked manual entry, show the strength meter, and — on an ENCRYPTED nest —
  // the manual-password warning (warn_manual_bridge_password). The mint-once
  // decision (kind + autoGenerate → fresh secret or clear) lives in shared Rust
  // via `resolveAutogeneratedBridgePassword` (mail-credentials.md § Mint-once
  // sequencing) — called only at this settled toggle edge, never again at submit,
  // so the persisted credential is byte-identical to what the user copied.
  // `applyAutogen` is only ever invoked while `isPlain` is true (selectPlain
  // guards its call, and the autogenerate toggle only renders `{#if isPlain}`),
  // so `kind` is always `'Plain'` here.
  function applyAutogen(): void {
    const resolved = resolveAutogeneratedBridgePassword('Plain', autoGenerate);
    if (resolved !== null) {
      passwordInput = resolved;
      showPassword = true; // reveal the generated secret so the user can copy it
    } else {
      passwordInput = '';
      showPassword = false;
    }
    showWeakWarning = warnManualBridgePassword(autoGenerate, nestEncrypted);
  }

  function cancelForm(): void {
    formOpen = false;
    tokenShown = '';
  }

  async function submitForm(): Promise<void> {
    if (!machine) return;
    const display_name = nameInput.trim() || 'Default';
    error = '';
    let secretBytes: Uint8Array;
    let tokenToShow = '';
    if (isPlain) {
      if (!passwordInput) {
        error = t.settings.mail.password_required;
        return;
      }
      secretBytes = new TextEncoder().encode(passwordInput);
    } else {
      // A fresh OAUTHBEARER token (shared Rust: 32 random bytes → 64 lowercase hex
      // chars) the human copies into their MUA; its UTF-8 bytes are the secret.
      tokenToShow = generateBridgeToken();
      secretBytes = new TextEncoder().encode(tokenToShow);
    }
    const kind = isPlain ? 'Plain' : 'OAuthBearer';
    // Decide enable-vs-add from the form's entry intent (linux `FormMode`), with a
    // hydrate-race guard:
    //  - 'add' (add-credential button) ⇒ AddCredential — the button renders only
    //    when a mailbox is provisioned, so the MSEK exists; this is correct for a
    //    CalDAV-only actor (where `snap.enabled` is false but a mailbox exists),
    //    the case a live-`snap.enabled` inference got wrong (it would EnableMail,
    //    turning email on).
    //  - 'enable' (enabled-toggle) ⇒ EnableMail, UNLESS `snap.enabled` already
    //    flipped true between open and submit (a slow hydrate / another tab), in
    //    which case AddCredential — EnableMail on an already-email-enabled actor
    //    errors.
    const variant =
      formIntent === 'add' || snap?.enabled ? 'AddCredential' : 'EnableMail';
    try {
      await machine.dispatch({ [variant]: { display_name, kind, secret: secretBytes } });
      applySnapshot();
      if (snap?.error) return; // leave the form open for retry
      if (tokenToShow) {
        // OAUTHBEARER success: reveal the one-time token; keep the form open.
        tokenShown = tokenToShow;
      } else {
        formOpen = false;
      }
    } catch (e) {
      applySnapshot();
      if (!error) error = e instanceof Error ? e.message : String(e);
    }
  }

  async function revokeCredential(credentialId: string): Promise<void> {
    if (!machine) return;
    try {
      await machine.dispatch({ RevokeCredential: { credential_id: credentialId } });
      applySnapshot();
    } catch (e) {
      applySnapshot();
      if (!error) error = e instanceof Error ? e.message : String(e);
    }
  }

  // Disable mail entirely (mail-settings.md § Disable mail): dispatch the shared
  // DisableMail (a unit `MailSettingsAction` → the bare string, like ResumeRotation)
  // — bulk soft-revoke every credential + clear the MSEK. The shared machine
  // deliberately does NOT touch the Admin-scoped deployment-wide set_mail_enabled
  // flag. The snapshot returns enabled:false with an empty credentials list; the
  // re-render flips the toggle back to "Enable mail". Cancel/dismiss is a no-op.
  async function confirmDisable(): Promise<void> {
    if (!machine) return;
    error = '';
    try {
      await machine.dispatch('DisableMail');
      applySnapshot();
    } catch (e) {
      applySnapshot();
      if (!error) error = e instanceof Error ? e.message : String(e);
    } finally {
      disableConfirmOpen = false;
    }
  }

  function cancelDisable(): void {
    disableConfirmOpen = false;
  }

  // Flip this nest's IMAP/CalDAV-serving for this actor. Non-optimistic: the
  // shared machine flips `serving_enabled` only after `set_mail_serving_enabled`
  // returns ok, so the rendered state (and the `data-state` attr the e2e reads)
  // reflects the nest's flag, not an optimistic local guess
  // (mail-settings.md § Local IMAP/CalDAV-serving toggle).
  async function onServeHereToggle(): Promise<void> {
    if (!machine || !snap) return;
    error = '';
    try {
      await machine.dispatch({ SetServingEnabled: { enabled: !snap.serving_enabled } });
      applySnapshot();
    } catch (e) {
      applySnapshot();
      if (!error) error = e instanceof Error ? e.message : String(e);
    }
  }

  async function confirmRotate(): Promise<void> {
    if (!machine) return;
    try {
      await machine.dispatch({ StartRotation: { excluded_credentials: [] } });
      applySnapshot();
      rotateOpen = false;
    } catch (e) {
      applySnapshot();
      if (!error) error = e instanceof Error ? e.message : String(e);
    }
  }

  async function resumeRotation(): Promise<void> {
    if (!machine) return;
    try {
      await machine.dispatch('ResumeRotation');
      applySnapshot();
    } catch (e) {
      applySnapshot();
      if (!error) error = e instanceof Error ? e.message : String(e);
    }
  }

  async function copyText(value: string): Promise<void> {
    try { await navigator.clipboard.writeText(value); } catch { /* headless / no perm */ }
  }
</script>

