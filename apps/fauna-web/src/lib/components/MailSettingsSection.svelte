  function muaUsername(template: string): string {
    return resolveMuaUsername(template, $identity?.handle ?? '');
  }

  function applySnapshot(): void {
    if (!machine) return;
    snap = machine.snapshot() as unknown as MailSnapshot;
    if (snap?.error) error = snap.error;
  }

  // The Forwarding section (mail-forwarding.md § Per-account "forward all",
  // § Per-account forward rate-limit) — plain
  // fauna.bridges.{get,set}_forward_* RPCs over the WsRpcClient, not the
  // MailSettingsMachine (the spam-threshold-override shape). Shown while mail is
  // enabled; both fields commit on Enter, the shared draft parsers check first,
  // and the field repaints from the nest's re-read, never the keystrokes.
  let forwardAllToInput = $state('');
  let forwardPerHourInput = $state('');
  let forwardCeiling = $state<number | null>(null);
  let forwardingLoaded = false;

  async function loadForwarding(secretHex: string): Promise<void> {
    forwardingLoaded = true;
    try {
      const address = await forwardAllToGet(secretHex);
      forwardAllToInput = address ?? '';
      const limit = await forwardPerHourGet(secretHex);
      forwardPerHourInput = String(limit.value);
      forwardCeiling = limit.ceiling;
    } catch (e) {
      forwardingLoaded = false;
      error = e instanceof Error ? e.message : String(e);
    }
  }

  $effect(() => {
    const id = $identity;
    if (snap?.enabled && id?.secretHex && !forwardingLoaded) void loadForwarding(id.secretHex);
  });

  async function commitForwardAllTo(): Promise<void> {
    const id = $identity;
    if (!id?.secretHex) return;
    error = '';
    const outcome = forwardAllToDraftOutcome(forwardAllToInput);
    if (outcome.kind === 'refused') {
      error = resolveLocalized(outcome.message);
      return;
    }
    try {
      const confirmed = await forwardAllToSet(id.secretHex, outcome.kind === 'set' ? outcome.address : null);
      forwardAllToInput = confirmed ?? '';
    } catch (e) {
      error = e instanceof Error ? e.message : String(e);
    }
  }

  async function commitForwardPerHour(): Promise<void> {
    const id = $identity;
    // No ceiling yet = the first read has not resolved: nothing to bound the
    // value by, so the commit is inert.
    if (!id?.secretHex || forwardCeiling === null) return;
    error = '';
    const outcome = forwardPerHourDraftOutcome(forwardPerHourInput, forwardCeiling);
    if (outcome.kind === 'refused') {
      error = resolveLocalized(outcome.message);
      return;
    }
    try {
      const confirmed = await forwardPerHourSet(id.secretHex, outcome.value);
      forwardPerHourInput = String(confirmed.value);
      forwardCeiling = confirmed.ceiling;
    } catch (e) {
      error = e instanceof Error ? e.message : String(e);
    }
  }

  // The receive / send switches, the automatic reply and the mailbox quota
  // (mail-policy-config.md § Tier 3; email-filters.md § The auto-respond
  // setting; imap-server.md § Composition with submission quota) — the tui
  // lead's shape. Each control is absent until its first read and repaints only
  // from the nest's confirmed re-read (the serve-here non-optimistic shape);
  // the quota's wording and the over-quota decision are the shared helpers'.
  let switches = $state<MailSwitches | null>(null);
  let autorespond = $state<AutoRespond | null>(null);
  let autorespondMessageInput = $state('');
  let quotas = $state<unknown>(null);
  let accountLoaded = false;

  function applyAutorespond(read: AutoRespond): void {
    // An off reply has no body; keep the draft so turning it back on sends the
    // last words.
    if (read.enabled) autorespondMessageInput = read.message;
    autorespond = read;
  }

  async function loadAccount(secretHex: string): Promise<void> {
    accountLoaded = true;
    try {
      switches = await mailSwitchesGet(secretHex);
      applyAutorespond(await emailAutorespondGet(secretHex));
      quotas = await mailQuotasGet(secretHex);
    } catch (e) {
      accountLoaded = false;
      error = e instanceof Error ? e.message : String(e);
    }
  }

  $effect(() => {
    const id = $identity;
    if (snap?.enabled && id?.secretHex && !accountLoaded) void loadAccount(id.secretHex);
  });

  // The flipped value comes from the last confirmed read; no read yet = inert.
  async function toggleSwitch(which: 'receive' | 'send' | 'scan'): Promise<void> {
    const id = $identity;
    if (!id?.secretHex || !switches) return;
    error = '';
    try {
      switches = which === 'receive'
        ? await mailSwitchesSet(id.secretHex, !switches.receive_enabled, null)
        : which === 'send'
          ? await mailSwitchesSet(id.secretHex, null, !switches.send_enabled)
          : await mailScanResultVisibleSet(id.secretHex, !switches.scan_result_visible);
    } catch (e) {
      error = e instanceof Error ? e.message : String(e);
    }
  }

  // Off needs no draft; on — the toggle or Enter on the message — runs the
  // shared draft check first, and a blank draft is refused on `error-message`.
  async function setAutorespond(on: boolean): Promise<void> {
    const id = $identity;
    if (!id?.secretHex) return;
    error = '';
    let message: string | null = null;
    if (on) {
      const outcome = autorespondMessageDraftOutcome(autorespondMessageInput);
      if (outcome.kind === 'refused') {
        error = resolveLocalized(outcome.message);
        return;
      }
      message = outcome.text;
    }
    try {
      applyAutorespond(await emailAutorespondSetAndReload(id.secretHex, message));
    } catch (e) {
      error = e instanceof Error ? e.message : String(e);
    }
  }

  function quotaText(q: unknown): string {
    const d = mailQuotaDisplay(q);
    return resolveComposed({ text: d.label, nested: { used: d.used, limit: d.limit } });
  }

