            <span class="warn small" data-testid={IDS.MAIL_ADD_CREDENTIAL_WEAK_PASSWORD_WARNING}>{t.settings.mail.weak_password_warning}</span>
          {/if}
        {/if}
      {:else}
        <!-- OAUTHBEARER one-time token reveal (shown only once). -->
        <p class="muted small">{t.settings.mail.token_warning}</p>
        <code class="mono token" data-testid={IDS.MAIL_ADD_CREDENTIAL_TOKEN_DISPLAY}>{tokenShown}</code>
        <button class="btn" data-testid={IDS.MAIL_ADD_CREDENTIAL_TOKEN_COPY_BUTTON} onclick={() => copyText(tokenShown)}>
          {t.settings.mail.copy_token}
        </button>
      {/if}

      <div class="form-actions">
        {#if !tokenShown}
          <button class="btn primary" data-testid={IDS.MAIL_ADD_CREDENTIAL_SUBMIT_BUTTON} onclick={submitForm}>
            {formIntent === 'enable' ? t.settings.mail.submit_enable : t.settings.mail.submit_add}
          </button>
        {/if}
        <button class="btn" data-testid={IDS.MAIL_ADD_CREDENTIAL_CANCEL_BUTTON} onclick={cancelForm}>
          {tokenShown ? t.settings.mail.done : t.settings.mail.cancel}
        </button>
      </div>
    </div>
  {/if}

  <!-- Rotate-keys confirm (inline reveal). -->
  {#if rotateOpen}
    <div class="form">
      <p class="muted small" data-testid={IDS.MAIL_ROTATE_KEYS_WARNING_TEXT}>{t.settings.mail.rotate_warning}</p>
      <div data-testid={IDS.MAIL_ROTATE_KEYS_EXCLUDE_LIST}>
        <!-- Per-credential exclude checkboxes; the e2e drives a no-exclusion rotation. -->
        {#each snap?.credentials ?? [] as c}
          <label class="exclude-row">
            <input type="checkbox" disabled />
            <span>{c.display_name}</span>
          </label>
        {/each}
      </div>
      <span class="muted small" data-testid={IDS.MAIL_ROTATE_KEYS_PROGRESS_INDICATOR}>{statusLabel(snap?.status, Boolean(snap?.enabled))}</span>
      <div class="form-actions">
        <button class="btn primary" data-testid={IDS.MAIL_ROTATE_KEYS_CONFIRM_BUTTON} onclick={confirmRotate}>
          {t.settings.mail.rotate_confirm}
        </button>
        <button class="btn" data-testid={IDS.MAIL_ROTATE_KEYS_CANCEL_BUTTON} onclick={() => { rotateOpen = false; }}>
          {t.settings.mail.cancel}
        </button>
      </div>
    </div>
  {/if}

  <!-- Disable-mail confirmation (destructive overlay — mail-settings.md § Disable
       mail). Opened by flipping the enabled-toggle off; confirming dispatches the
       shared DisableMail (bulk-revoke every credential + clear the MSEK). Cancel is
       a no-op — the toggle was never actually flipped off. The dialog carries
       `mail-settings-disable-confirm` for e2e discovery/scoping; the destructive
       button carries `mail-settings-disable-confirm-button`. -->
  {#if disableConfirmOpen}
    <div class="overlay" role="dialog">
      <div class="dialog" data-testid={IDS.MAIL_SETTINGS_DISABLE_CONFIRM}>
        <p><strong>{t.settings.mail.disable_title}</strong></p>
        <p>{t.settings.mail.disable_warning}</p>
        <div class="dialog-actions">
          <button class="btn danger" data-testid={IDS.MAIL_SETTINGS_DISABLE_CONFIRM_BUTTON} onclick={confirmDisable}>
            {t.settings.mail.disable_confirm}
          </button>
          <button class="btn" onclick={cancelDisable}>{t.settings.mail.cancel}</button>
        </div>
      </div>
    </div>
  {/if}

  <!-- Mail-disabled view: heading + toggle + a short explanation sentence
       (mail-settings.md § "When mail is disabled: only the toggle + heading + a
       short explanation sentence"). Gated on !mailbox to match the linux lead and
       android (apps/fauna-linux/src/settings/mail.rs:215;
       MailSettingsScreen.kt's `if (!mailbox)` arm). -->
  {#if !mailbox}
    <p class="muted section-description">{t.settings.mail.section_description}</p>
  {/if}

  <!-- Per-credential rows. Part of the credential-management section, so the list
       renders whenever a mailbox is provisioned (email OR CalDAV), matching the
       linux lead's `credentials_group` gate. Title + empty-state mirror the linux
       lead (`CREDENTIALS_TITLE` / `CREDENTIALS_EMPTY`) and android. -->
  {#if mailbox}
  <div class="creds" data-testid={IDS.MAIL_SETTINGS_CREDENTIALS_LIST}>
    <h3 class="creds-title">{t.settings.mail.credentials_title}</h3>
    {#if (snap?.credentials ?? []).length === 0}
      <p class="muted small creds-empty">{t.settings.mail.credentials_empty}</p>
    {/if}
    {#each snap?.credentials ?? [] as c}
      <div class="cred-item" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM}>
        <span class="cred-name" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_NAME}>{c.display_name}</span>
        <!-- Succession's compromised state (`mail-credentials.md` § Rotation and
             recovery → Succession) — the row survives so the user knows what to
             set up again, but must never read as usable. Mirrors the linux lead's
             placement: directly under the name, above the MUA username. -->
        {#if c.revoked}
          <span class="warn small" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_REVOKED}>
            {t.settings.mail.credential_revoked}
          </span>
        {/if}
        <span class="badge" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_TYPE}>
          {resolveLocalized(credentialKindBadge(c.kind))}
        </span>
        <span class="muted small" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_CREATED_AT}>{c.created_at}</span>
        <span class="muted small" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_LAST_USED_AT}>—</span>
        <button class="btn danger small" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_REVOKE_BUTTON} onclick={() => revokeCredential(c.credential_id)}>
          {t.settings.mail.revoke}
        </button>
        <!-- The exact MUA username this credential logs in with (mail-settings.md
             § Credentials list) — copied verbatim into a third-party MUA. -->
        <div class="cred-field">
          <span class="field-label">{t.settings.mail.mua_username}</span>
          <code class="mono" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_USERNAME}>{muaUsername(c.mua_username)}</code>
          <button class="btn small" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_COPY_USERNAME} onclick={() => copyText(muaUsername(c.mua_username))}>
            {t.settings.mail.copy_username}
          </button>
        </div>
        <!-- The credential's secret: hidden by default; revealed on demand from
             the client's own `fauna.state.mail` entries (never in the snapshot). -->
        <div class="cred-field">
          <span class="field-label">{t.settings.mail.secret_label}</span>
          <code class="mono secret" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_SECRET}>{revealedSecrets[c.credential_id] ?? ''}</code>
          <button class="btn small" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_REVEAL_SECRET} onclick={() => toggleSecret(c.credential_id)}>
            {c.credential_id in revealedSecrets ? t.settings.mail.hide_secret : t.settings.mail.reveal_secret}
          </button>
          <button class="btn small" data-testid={IDS.MAIL_SETTINGS_CREDENTIAL_ITEM_COPY_SECRET} onclick={() => copyText(revealedSecrets[c.credential_id] ?? '')}>
            {t.settings.mail.copy_secret}
          </button>
        </div>
      </div>
    {/each}
  </div>
  {/if}

  <!-- Connection details (read-only; each field copyable). The block renders
       whenever a mailbox is provisioned (email OR CalDAV); PER-PROTOCOL gating
       WITHIN it (mail-settings.md § CalDAV-only mailbox;
       §2, mirroring the linux lead): the IMAP/SMTP rows on `enabled`, the CalDAV
       rows on `caldav_enabled`, and username/auth (the one shared credential)
       whenever a mailbox is provisioned. (`mailbox && snap` narrows `snap` for the
       non-optional `snap.mua` reads below.) -->
  {#if mailbox && snap}
    <div class="mua" data-testid={IDS.MAIL_SETTINGS_MUA_INSTRUCTIONS}>
      <p class="mua-title">{t.settings.mail.mua_title}</p>
      {#if snap.enabled}
        <div class="mua-row">
          <span class="field-label">{t.settings.mail.mua_imap_host}</span>
          <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_IMAP_HOST}>{snap.mua.imap_host}</code>
        </div>
        <div class="mua-row">
          <span class="field-label">{t.settings.mail.mua_imap_port}</span>
          <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_IMAP_PORT}>{snap.mua.imap_port}</code>
        </div>
        <div class="mua-row">
          <span class="field-label">{t.settings.mail.mua_smtp_host}</span>
          <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_SMTP_HOST}>{snap.mua.smtp_host}</code>
        </div>
        <div class="mua-row">
          <span class="field-label">{t.settings.mail.mua_smtp_port}</span>
          <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_SMTP_PORT}>{snap.mua.smtp_port}</code>
        </div>
      {/if}
      {#if snap.caldav_enabled}
        <!-- CalDAV server URL — the one shared credential AUTHs CalDAV too -->
        <div class="mua-row">
          <span class="field-label">{t.settings.mail.mua_caldav_host}</span>
          <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_CALDAV_HOST}>{snap.mua.caldav_host}</code>
        </div>
        <div class="mua-row">
          <span class="field-label">{t.settings.mail.mua_caldav_port}</span>
          <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_CALDAV_PORT}>{snap.mua.caldav_port}</code>
        </div>
      {/if}
      {#if snap.serves_webdav_set}
        <!-- WebDAV collection root — one full URL (no SRV autodiscovery exists),
             shown once the actor actually serves a folder over WebDAV. -->
        <div class="mua-row">
          <span class="field-label">{t.settings.mail.mua_webdav_url}</span>
          <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_WEBDAV_URL}>{snap.mua.webdav_url}</code>
        </div>
      {/if}
      <div class="mua-row">
        <span class="field-label">{t.settings.mail.mua_username}</span>
        <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_USERNAME_FORMAT}>
          {muaUsername(snap.credentials[0]?.mua_username ?? snap.mua.username_format)}
        </code>
      </div>
      <div class="mua-row">
        <span class="field-label">{t.settings.mail.mua_auth}</span>
        <code class="mono" data-testid={IDS.MAIL_SETTINGS_MUA_AUTH_MECHANISM}>{snap.mua.auth_mechanism}</code>
      </div>
    </div>
  {/if}
