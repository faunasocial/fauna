def test_no_test_fake_implements_a_generated_interface_directly():
    declared, fake_bases, violations = _scan_test_tree(_APP_DIR, _TESTS_DIR)

    # Non-vacuity: a moved directory or a broken walk must not turn this into a pass.
    assert "IStringLocalizer" in declared, "scan did not read the hand-written C# under FaunaApp/"
    assert fake_bases, "scan found no `*FakeBase` inheritor — the test tree was not read"

    assert not violations, (
        "test fakes must inherit the generated `<X>FakeBase`, never implement a UniFFI "
        "interface directly — a new interface member must compile clean, not CS0535 "
        "(docs/goal/architecture/apps/windows.md § Workspace Layout). Change the base "
        "and `override` only the members the test exercises:\n"
        + "\n".join(
            f"  {path}: {type_name} : {iface}  ->  {iface[1:]}FakeBase"
            for path, type_name, iface in violations
        )
        + "\nIf the interface is genuinely not UniFFI-generated (a BCL / NuGet interface), "
        "name it in `_EXTERNAL_INTERFACES` in this file, with the reason."
    )
