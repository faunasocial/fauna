# ── Migration invariant: no test class implements a generated UniFFI interface
#    directly — every fake inherits its generated `<X>FakeBase`. ──────────────────
#
# The rule is ratified in docs/goal/architecture/apps/windows.md § Workspace Layout
# ("Test fakes for generated UniFFI interfaces inherit the generated `<X>FakeBase`,
# never implement the interface directly"). A hand-listed set of fakes cannot hold it:
# the list this test used to carry named three, and eleven more fakes were written
# against the raw interface afterwards — each one growth away from the whole-project
# CS0535 the base classes exist to end (`FakeMailExportMachine`, 2026-09-21).
#
# The gitignored bindings are not guaranteed present here, so the scan cannot ask "is
# this interface UniFFI-generated?". It asks the tracked tree the inverse question: an
# interface a test class implements is legitimate only if it is DECLARED in tracked
# hand-written C# under FaunaApp/ (a project seam such as `IStringLocalizer`) or is a
# BCL interface. Anything else can only have come from the generated bindings, and a
# fake for it must inherit `<X>FakeBase`. Project seams need no list — the scan finds
# them; only a genuinely external interface is named in `_EXTERNAL_INTERFACES`.

_APP_DIR = os.path.join(_REPO, "apps", "fauna-windows", "FaunaApp")
_TESTS_DIR = os.path.join(_APP_DIR, "FaunaApp.Tests")

# Interfaces a fake may implement directly because they are declared neither by the
# generated bindings nor anywhere in this tree. Add a name only for a BCL / NuGet
# interface, with the reason.
_EXTERNAL_INTERFACES = frozenset(
    {
        "IDisposable",  # BCL — fixtures, and `Disposable*` doubles that also inherit a base
        "INotifyPropertyChanged",  # BCL — observer test doubles
    }
)

# `Generated/` is gitignored output (the bindings and FakeBases.g.cs itself, whose bases
# implement every interface directly by design); `bin`/`obj` are build output.
_SKIPPED_DIRS = frozenset({"Generated", "bin", "obj"})

_INTERFACE_DECL_RE = re.compile(r"\binterface\s+(I[A-Z]\w*)")
_TYPE_KEYWORD_RE = re.compile(r"\b(?:class|struct|record)\s+\w+")
_INTERFACE_NAME_RE = re.compile(r"^I[A-Z]\w*$")


def _strip_line_comments(text):
    # Line comments only: a `/*` inside a string literal (`"**/*.cs"`) would otherwise
    # open a block comment that swallows the rest of the file and hides violations.
    return re.sub(r"//[^\n]*", "", text)


def _skip_ws(text, i):
    while i < len(text) and text[i].isspace():
        i += 1
    return i


def _skip_group(text, i, open_ch, close_ch):
    """Index just past the balanced group opening at text[i]; `i` unchanged if none."""
    if i >= len(text) or text[i] != open_ch:
        return i
    depth = 0
    while i < len(text):
        if text[i] == open_ch:
            depth += 1
        elif text[i] == close_ch:
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return i


def _split_bases(base_list):
    """`A, B<C, D>, Ns.E` -> ['A', 'B', 'E'] (top-level commas; generics and namespace
    qualification dropped)."""
    bases, depth, current = [], 0, []
    for ch in base_list:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            bases.append("".join(current))
            current = []
        else:
            current.append(ch)
    bases.append("".join(current))
    names = []
    for b in bases:
        b = re.sub(r"<.*", "", b.strip(), flags=re.DOTALL)  # drop generic arguments
        if b:
            names.append(b.rsplit(".", 1)[-1].strip())  # drop namespace qualification
    return names


def _declared_bases(text):
    """Yield (type_name, [base names]) for every class/struct/record header in `text`
    that has a base list. Walks the header (generics, primary constructor, base list up
    to `{`/`;`/`where`) instead of one regex, so multi-line base lists, primary
    constructors and constraint clauses all resolve."""
    for m in _TYPE_KEYWORD_RE.finditer(text):
        name = m.group(0).split()[-1]
        i = _skip_ws(text, m.end())
        i = _skip_ws(text, _skip_group(text, i, "<", ">"))
        i = _skip_ws(text, _skip_group(text, i, "(", ")"))
        if i >= len(text) or text[i] != ":":
            continue
        end = i + 1
        depth = 0
        while end < len(text):
            ch = text[end]
            if ch == "<":
                depth += 1
            elif ch == ">":
                depth -= 1
            elif depth == 0 and ch in "{;":
                break
            end += 1
        base_list = re.split(r"\bwhere\b", text[i + 1 : end])[0]
        yield name, _split_bases(base_list)


def _cs_files(root):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in _SKIPPED_DIRS]
        for fn in sorted(filenames):
            if fn.endswith(".cs"):
                yield os.path.join(dirpath, fn)


def _read_cs(path):
    with open(path, encoding="utf-8") as fh:
        return _strip_line_comments(fh.read())


def _scan_test_tree(app_dir, tests_dir):
    """-> (declared_interfaces, inherited_fake_bases, violations). A violation is
    (file relative to tests_dir, type name, interface) for an interface that is neither
    declared in `app_dir`'s hand-written C# nor in `_EXTERNAL_INTERFACES`."""
    declared = set()
    for path in _cs_files(app_dir):
        declared.update(_INTERFACE_DECL_RE.findall(_read_cs(path)))
    allowed = declared | _EXTERNAL_INTERFACES

    fake_bases, violations = set(), []
    for path in _cs_files(tests_dir):
        for type_name, bases in _declared_bases(_read_cs(path)):
            for base in bases:
                if base.endswith("FakeBase"):
                    fake_bases.add(base)
                elif _INTERFACE_NAME_RE.match(base) and base not in allowed:
                    violations.append((os.path.relpath(path, tests_dir), type_name, base))
    return declared, fake_bases, violations


def _synthetic_tree(tmp_path, files):
    app = tmp_path / "FaunaApp"
    for rel, text in files.items():
        p = app / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return str(app), str(app / "FaunaApp.Tests")


def _violating(tmp_path, files):
    _, _, violations = _scan_test_tree(*_synthetic_tree(tmp_path, files))
    return sorted((t, i) for _, t, i in violations)


